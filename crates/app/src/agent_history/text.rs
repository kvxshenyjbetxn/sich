//! Text helpers shared by the Claude and Codex parsers: one-line normalization, the filter for
//! text the harness injected (not typed by the user), and timestamps.

use serde::Deserialize;
use serde_json::Value;

/// Control characters become spaces and whitespace runs collapse; cut to `max` chars with `…`.
pub(super) fn one_line(text: &str, max: usize) -> String {
    let joined = text
        .chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect::<String>()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ");
    if joined.chars().count() <= max {
        return joined;
    }
    let mut cut: String = joined.chars().take(max.saturating_sub(1)).collect();
    cut.truncate(cut.trim_end().len());
    cut.push('\u{2026}');
    cut
}

/// Prefixes of user-role text that the harness wrote, not the user.
const INJECTED_PREFIXES: [&str; 14] = [
    "<command-",
    "<local-command-",
    "<system-reminder>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<user-prompt-submit-hook>",
    "<environment_context>",
    "<user_instructions>",
    "<user_action>",
    "<turn_aborted>",
    "# AGENTS.md instructions",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted by user",
];

pub(super) fn is_injected(text: &str) -> bool {
    let text = text.trim_start();
    INJECTED_PREFIXES.iter().any(|prefix| text.starts_with(prefix))
}

/// The text blocks of a message `content` (a plain string or an array of blocks), joined by a
/// newline. Tool results, images and thinking blocks carry no text here: `None` when nothing is left.
pub(super) fn content_text(content: &Value) -> Option<String> {
    let text = match content {
        Value::String(s) => s.clone(),
        Value::Array(blocks) => blocks
            .iter()
            .filter_map(|block| match block {
                Value::String(s) => Some(s.as_str()),
                Value::Object(map) => {
                    let kind = map.get("type").and_then(Value::as_str).unwrap_or("text");
                    if matches!(kind, "text" | "input_text" | "output_text") {
                        map.get("text").and_then(Value::as_str)
                    } else {
                        None
                    }
                }
                _ => None,
            })
            .collect::<Vec<_>>()
            .join("\n"),
        _ => return None,
    };
    (!text.trim().is_empty()).then_some(text)
}

/// RFC 3339 timestamp to unix milliseconds; `None` for garbage or dates before 1970.
pub(super) fn parse_ms(raw: &str) -> Option<u64> {
    let parsed = chrono::DateTime::parse_from_rfc3339(raw.trim()).ok()?;
    u64::try_from(parsed.timestamp_millis()).ok()
}

/// serde helper: a string field, or `None` when it is of another type.
pub(super) fn lenient_string<'de, D: serde::Deserializer<'de>>(d: D) -> Result<Option<String>, D::Error> {
    Ok(match Value::deserialize(d)? {
        Value::String(s) => Some(s),
        _ => None,
    })
}

/// serde helper: a bool field, or `None` when it is of another type.
pub(super) fn lenient_bool<'de, D: serde::Deserializer<'de>>(d: D) -> Result<Option<bool>, D::Error> {
    Ok(Value::deserialize(d)?.as_bool())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn one_line_collapses_and_truncates() {
        assert_eq!(one_line("  a\n\tb   c ", 50), "a b c");
        assert_eq!(one_line("abcdef", 6), "abcdef");
        assert_eq!(one_line("abcdefg", 6), "abcde\u{2026}");
        assert_eq!(one_line("ab cdefg", 4), "ab\u{2026}");
        assert_eq!(one_line("ї".repeat(10).as_str(), 4).chars().count(), 4);
        assert_eq!(one_line("", 5), "");
    }

    #[test]
    fn injected_text_is_recognized() {
        for text in [
            "<command-name>/clear</command-name>",
            "  <local-command-stdout>x</local-command-stdout>",
            "<system-reminder>be careful</system-reminder>",
            "<environment_context>cwd</environment_context>",
            "# AGENTS.md instructions for /repo",
            "[Request interrupted by user]",
        ] {
            assert!(is_injected(text), "{text}");
        }
        for text in ["fix the bug", "use <command-x> in docs", "", "<div>html</div>"] {
            assert!(!is_injected(text), "{text}");
        }
    }

    #[test]
    fn content_text_takes_text_blocks_only() {
        assert_eq!(content_text(&json!("hi")), Some("hi".into()));
        assert_eq!(content_text(&json!("  ")), None);
        let blocks = json!([
            {"type": "tool_result", "content": "big output"},
            {"type": "text", "text": "one"},
            {"type": "image", "source": {}},
            {"type": "input_text", "text": "two"},
            {"type": "thinking", "thinking": "hmm"}
        ]);
        assert_eq!(content_text(&blocks), Some("one\ntwo".into()));
        assert_eq!(content_text(&json!([{"type": "tool_result", "content": "x"}])), None);
        assert_eq!(content_text(&json!(5)), None);
        assert_eq!(content_text(&json!(null)), None);
    }

    #[test]
    fn timestamps_parse_to_unix_ms() {
        assert_eq!(parse_ms("1970-01-01T00:00:01.500Z"), Some(1500));
        assert_eq!(parse_ms("2026-11-11T13:43:45.685Z"), Some(1_794_404_625_685));
        assert_eq!(parse_ms("1969-12-31T23:59:59Z"), None);
        assert_eq!(parse_ms("yesterday"), None);
    }
}
